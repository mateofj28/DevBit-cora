-- Registro de quién cambió qué. Es solo de escritura (no se edita ni se borra desde la app).
-- user_name guarda una copia del nombre para que el historial sobreviva a cambios o bajas de usuarios.
-- project_id no tiene clave foránea a propósito: el historial se conserva aunque se elimine un proyecto.
CREATE TABLE IF NOT EXISTS audit_log (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id INTEGER,
  user_name TEXT NOT NULL,
  action TEXT NOT NULL,
  entity TEXT NOT NULL CHECK (entity IN ('project', 'incident', 'user')),
  entity_id INTEGER NOT NULL,
  project_id INTEGER,
  summary TEXT NOT NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS audit_log_project_idx ON audit_log (project_id, id DESC);
