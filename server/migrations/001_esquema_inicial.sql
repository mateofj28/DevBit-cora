CREATE TABLE IF NOT EXISTS users (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  email TEXT NOT NULL,
  name TEXT NOT NULL,
  password_hash TEXT NOT NULL,
  role TEXT NOT NULL CHECK (role IN ('editor', 'lector')),
  active BOOLEAN NOT NULL DEFAULT TRUE,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE UNIQUE INDEX IF NOT EXISTS users_email_uq ON users (lower(email));

CREATE TABLE IF NOT EXISTS projects (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name TEXT NOT NULL,
  summary TEXT NOT NULL,
  status TEXT NOT NULL CHECK (status IN ('activo', 'en_desarrollo', 'mantenimiento', 'pausado', 'finalizado')),
  owner TEXT NOT NULL,
  repo_url TEXT,
  production_url TEXT,
  docs_url TEXT,
  archived BOOLEAN NOT NULL DEFAULT FALSE,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE UNIQUE INDEX IF NOT EXISTS projects_name_uq ON projects (lower(name));

CREATE TABLE IF NOT EXISTS technologies (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name TEXT NOT NULL,
  kind TEXT NOT NULL CHECK (kind IN ('lenguaje', 'framework', 'base_de_datos', 'otro'))
);
CREATE UNIQUE INDEX IF NOT EXISTS technologies_name_uq ON technologies (lower(name));

CREATE TABLE IF NOT EXISTS providers (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name TEXT NOT NULL
);
CREATE UNIQUE INDEX IF NOT EXISTS providers_name_uq ON providers (lower(name));

CREATE TABLE IF NOT EXISTS project_technologies (
  project_id INTEGER NOT NULL REFERENCES projects(id) ON DELETE CASCADE,
  technology_id INTEGER NOT NULL REFERENCES technologies(id),
  PRIMARY KEY (project_id, technology_id)
);

CREATE TABLE IF NOT EXISTS services (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  project_id INTEGER NOT NULL REFERENCES projects(id) ON DELETE CASCADE,
  name TEXT NOT NULL,
  component TEXT NOT NULL CHECK (component IN ('frontend', 'backend', 'base_de_datos', 'almacenamiento', 'otro')),
  provider_id INTEGER NOT NULL REFERENCES providers(id),
  url TEXT,
  notes TEXT
);
CREATE INDEX IF NOT EXISTS services_project_idx ON services (project_id);

CREATE TABLE IF NOT EXISTS incidents (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  project_id INTEGER NOT NULL REFERENCES projects(id) ON DELETE CASCADE,
  title TEXT NOT NULL,
  manifestation TEXT NOT NULL,
  cause TEXT NOT NULL DEFAULT '',
  resolution TEXT NOT NULL DEFAULT '',
  improvement TEXT NOT NULL DEFAULT '',
  occurred_on DATE NOT NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS incidents_project_idx ON incidents (project_id);
